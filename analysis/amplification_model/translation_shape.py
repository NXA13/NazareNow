def pin_against_shipped(shipped: Candidate, parameters: dict) -> str:
    """Refuse to report anything unless the `shipped` candidate really is the shipped one.

    Every figure in this module is a comparison against `shipped`, and `shipped` is re-derived
    here from the overlap hours rather than read out of `amplification.json` — so that all five
    candidates are built by one piece of code from one set of hours and differ only in their
    subset. That is worth having, and it is only worth having if the re-derivation lands on the
    constants the backend actually applies. If it does not, the whole table is measuring this
    module against itself.
    """
    published = parameters["translations"]
    for variable, shape in (
        ("significant_wave_height_m", shipped.height),
        ("swell_period_s", shipped.period),
    ):
        segment = shape.segments[0]
        for label, here, there in (
            ("slope", segment.slope, published[variable]["slope"]),
            ("intercept", segment.intercept, published[variable]["intercept"]),
            ("residual RMSE", segment.residual_rmse, published[variable]["residual_rmse"]),
            ("hours", float(segment.n), float(published[variable]["fitted_on_hours"])),
        ):
            if abs(here - there) > 1e-9:
                raise RuntimeError(
                    f"the re-derived shipped Translation does not match amplification.json: "
                    f"{variable} {label} is {here!r} here against {there!r} shipped. Either the "
                    "overlap cache has changed since the model was exported, or this module "
                    "fits a different subset from `measure.fit_translations`."
                )
    return "The `shipped` candidate re-derives amplification.json's constants exactly.\n"


def pin_against_served_path(
    shipped: Candidate, parameters, frame, target: np.ndarray, trials: int
) -> str:
    """Reproduce `output/served_path_scores.csv` by running this module as the shipped path.

    The generalisation here separates two things `served_path.py` holds together — the
    transform that generates the operational series and the transform the model inverts — and
    that separation is the whole argument of this module. Collapsing it back, by generating
    with `shipped` and inverting with `shipped`, must land exactly on the published served
    figures. If it does not, the generalisation changed the arithmetic rather than only
    widening it, and every alternative scored against those figures would be scored against a
    different calculation that happens to look alike.
    """
    _, collected = score_candidates(
        parameters,
        frame,
        target,
        [shipped],
        Reconstruction(generator=shipped),
        trials=trials,
    )
    published = {row["subset"]: row for row in _published_served()}
    for band, results in collected.items():
        if band not in published:
            continue
        for label, key in (("baseline", "served_baseline_mae"), ("shipped", "served_learned_mae")):
            here = float(np.mean(results[label]))
            there = float(published[band][key])
            if abs(here - there) > 5e-5:
                raise RuntimeError(
                    f"scored as the shipped path, {band} {label} is {here:.4f} here against "
                    f"{there:.4f} in served_path_scores.csv — the generalisation moved the "
                    "arithmetic, not just its inputs"
                )
    return (
        f"Run as the shipped path it reproduces served_path_scores.csv over {trials} trials, "
        "so the\nalternatives below are comparable with the published served figures rather "
        "than a\nseparate calculation.\n"
    )


def _published_served() -> list[dict]:
    with served_path.OUTPUT.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _write(path: Path, rows: list[dict]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return path


def reconstructions(by_name: dict[str, Candidate], generator_name: str) -> list[Reconstruction]:
    """Every version of the served path this module reports, in the order they build on each other.

    The published served figures come from the first. The headline comes from the second. The
    difference between the two is the reconstruction's own contribution, which is the quantity
    #52 needs and which no single run can show.
    """
    generator = by_name[generator_name]
    return [
        Reconstruction(generator=by_name["shipped"]),
        Reconstruction(generator=generator),
        Reconstruction(generator=generator, scatter="none"),
        Reconstruction(generator=generator, scatter="proportional"),
    ]


