# Scoring on the served path
# ---------------------------------------------------------------------------------------


Scatter = Literal["flat", "proportional", "none"]
"""What the reconstruction adds on top of the transform.

`flat` is `served_path.py`'s assumption — the residual is independent of sea state. `none`
isolates the measured offset from the assumed scatter. `proportional` redistributes the same
residual so that it grows with the sea, which is the reading that would make a conclusion an
artefact of the assumption rather than a property of the system.
"""


@dataclass(frozen=True)
class Reconstruction:
    """How the operational series a candidate is scored against is generated.

    Separated from the transform under test so the two roles cannot be confused. The
    generator stands in for what Open-Meteo would have read; the candidate is what the
    Amplification Model would invert. `served_path.py` uses the shipped line for both, which
    is right for baseline-against-learned and circular for shape-against-shape.
    """

    generator: Candidate
    scatter: Scatter = "flat"

    @property
    def label(self) -> str:
        return f"{self.generator.name} / scatter {self.scatter}"

    def draw(self, rng, shape: Shape, values: np.ndarray) -> np.ndarray:
        operational = shape.apply(values)
        if self.scatter == "none":
            return operational
        spread = shape.scatter(values)
        if self.scatter == "proportional":
            # Same total residual energy, redistributed so that it grows with the sea
            # instead of sitting flat across it. The alternative reading of the same
            # measurement, and the one that would make the sign change an artefact.
            spread = spread * (values / max(float(np.mean(values)), 1e-9))
        return operational + rng.normal(0.0, 1.0, len(values)) * spread


def score_candidates(
    parameters: dict,
    frame,
    target: np.ndarray,
    candidates: list[Candidate],
    reconstruction: Reconstruction,
    trials: int = served_path.TRIALS,
    seed: int = served_path.SEED,
) -> tuple[dict[str, np.ndarray], dict[str, dict[str, list[float]]]]:
    """Every candidate against one generated series, band by band.

    One `rng` and one generated series per trial, shared by every candidate, so the candidates
    differ by their transform and not by their draw. The baseline never inverts anything, so
    its MAE is identical across candidates by construction — which is what makes the learned
    column comparable down the table.
    """
    ibi_hs = frame["hindcast_combined_sea_height_m"].to_numpy()
    ibi_period = frame["swell_period_s"].to_numpy()
    rng = np.random.default_rng(seed)
    bands = served_path.subsets(frame, target)

    collected: dict[str, dict[str, list[float]]] = {
        name: {"baseline": []} | {candidate.name: [] for candidate in candidates} for name in bands
    }

    for _ in range(trials):
        operational_hs = reconstruction.draw(rng, reconstruction.generator.height, ibi_hs)
        operational_period = reconstruction.draw(rng, reconstruction.generator.period, ibi_period)
        predictions = {"baseline": operational_hs}
        for candidate in candidates:
            predictions[candidate.name] = served_path.predict(
                parameters,
                candidate.height.invert(operational_hs),
                candidate.period.invert(operational_period),
                frame,
            )
        for name, mask in bands.items():
            for label, predicted in predictions.items():
                collected[name][label].append(float(np.abs(predicted[mask] - target[mask]).mean()))
    return bands, collected


