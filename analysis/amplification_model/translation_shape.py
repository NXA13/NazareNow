INPUT_BANDS = ((0.0, 1.0), (1.0, 2.0), (2.0, 3.0), (3.0, 4.0), (4.0, 5.0), (5.0, 6.0), (6.0, 99.0))
"""Bands of *reanalysis Combined Sea* over the overlap hours.

Not the bands the rest of this module reports. Those are measured-target bands over held-out
hours at the buoy; these are input bands over the hours where both products reported, which is
the only place a transform between them can be checked at all.
"""


@dataclass(frozen=True)
class PairingError:
    """One candidate's error against the reading it is trying to predict, in one band."""

    candidate: str
    quantity: str
    band: str
    n: int
    bias: float
    rmse: float


def pairing_error(hours: list[measure.Paired], candidates: list[Candidate]) -> list[PairingError]:
    """How far each transform lands from the operational reading it claims to produce.

    **This is the one measurement here that is not a bound.** Everything downstream depends on
    reconstructing a series Open-Meteo never published at this location. This does not: both
    products really reported on all 35,064 of these hours, so the error of a transform between
    them is observed. If extrapolating the shipped Translation below its fitted range is a real
    defect, it is visible here, in the band where it is extrapolating, with no assumption in
    the way.

    Bias is kept signed and reported beside RMSE for the reason `measure.score` keeps them
    apart: a transform that is noisy in a band and one that is displaced through it are
    different failures, and only the second is what extrapolating a fitted line does.
    """
    combined = np.array([h.reanalysis_combined_sea for h in hours])
    columns = _columns(hours)

    rows: list[PairingError] = []
    for quantity, (_, _, pick) in PAIRINGS.items():
        xs, ys = (np.array(column) for column in columns[quantity])
        for lower, upper in (*INPUT_BANDS, (0.0, 99.0)):
            mask = (combined >= lower) & (combined < upper)
            if not mask.any():
                continue
            band = "all hours" if (lower, upper) == (0.0, 99.0) else f"{lower:g}-{upper:g} m"
            for candidate in candidates:
                errors = pick(candidate).apply(xs[mask]) - ys[mask]
                rows.append(
                    PairingError(
                        candidate=candidate.name,
                        quantity=quantity,
                        band=band,
                        n=int(mask.sum()),
                        bias=float(np.mean(errors)),
                        rmse=float(np.sqrt(np.mean(errors**2))),
                    )
                )
    return rows


