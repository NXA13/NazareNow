def shipped_candidate(hours: list[measure.Paired]) -> Candidate:
    """The pairing `measure.fit_translations` actually ships, read out of its own table.

    Built from `measure.FITTINGS` rather than restated here as a subset of its own. Since #58
    the two quantities are fitted on different subsets, so there is no single predicate that
    reproduces the shipped pairing — and writing one out by hand would reintroduce exactly the
    drift `pin_against_shipped` exists to catch. Reading the source of truth means this cannot
    disagree with what ships unless the fitting itself changed.
    """
    shapes: dict[str, Shape] = {}
    for fitting in measure.FITTINGS:
        subset = fitting.hours(hours)
        if len(subset) < 2:
            raise RuntimeError(
                f"{fitting.variable}: {len(subset)} hours match {fitting.regime}, which is not "
                "enough to fit the line that ships"
            )
        shapes[fitting.variable] = fit_line(
            fitting.variable,
            "shipped",
            fitting.regime,
            [fitting.reanalysis_side(h) for h in subset],
            [fitting.operational_side(h) for h in subset],
        )
    return Candidate(
        name="shipped",
        height=shapes["significant_wave_height_m"],
        period=shapes["swell_period_s"],
    )


PAIRINGS: dict[
    str,
    tuple[
        Callable[[measure.Paired], float],
        Callable[[measure.Paired], float],
        Callable[[Candidate], Shape],
    ],
] = {
    "significant_wave_height_m": (
        lambda h: h.reanalysis_combined_sea,
        lambda h: h.operational_combined_sea,
        lambda candidate: candidate.height,
    ),
    "swell_period_s": (
        lambda h: h.combined_period,
        lambda h: h.operational_period,
        lambda candidate: candidate.period,
    ),
}
"""The two quantities a Translation is fitted between, and where each lives.

Named once because several places here need it and they must not drift: the alternative
candidates' fitting, the error measurement in section 2, and the restatement at scoring time.
Two of them reading the pairing differently is exactly the class of defect `served_path.check`
exists to catch between the two feature encodings.

**The `shipped` candidate does not use this table**, and deliberately so: since #58 it is built
from `measure.FITTINGS`, which carries the same two accessors for the two shipped quantities
alongside the subset each is fitted on. The accessors agree today, and pinning `shipped` to the
source of truth rather than to a local copy is what makes `pin_against_shipped` able to detect
it if they ever stop agreeing. The duplication is the point; this table exists to describe
*alternatives*, which `measure.py` knows nothing about.
"""


def _columns(hours: list[measure.Paired]) -> dict[str, tuple[list[float], list[float]]]:
    """Each pairing drawn out of a subset of hours, ready to fit."""
    return {
        quantity: ([source(h) for h in hours], [target(h) for h in hours])
        for quantity, (source, target, _) in PAIRINGS.items()
    }


def build_candidates(hours: list[measure.Paired]) -> list[Candidate]:
    """Every shape under test, fitted on the same overlap hours.

    Three families, and they answer different questions. `PERIOD_SUBSETS` holds height at the
    shipped fit and moves the period subset alone — that is #60's question, and no `SUBSETS`
    row answers it. `SUBSETS` moves both transforms together onto one subset. The regime-aware
    candidate is a shape change rather than a subset change.

    The regime-aware candidate hinges the **height** transform only, and takes the all-hours
    line for period. Hinging the period transform on its own period has no principled knot,
    and hinging it on Combined Sea — the regime that actually matters — would make the
    restated period jump as the sea crosses 3 m, which is a worse defect than the one being
    fixed. Combined Sea is also where the question lives: it carries a standardised
    coefficient of 1.089 against swell period's 0.057 (`output/feature_reliance.csv`).
    """

    def fittable(name: str, predicate: Callable[[measure.Paired], bool]) -> list[measure.Paired]:
        """The hours a candidate is fitted on, refused loudly if a line cannot be drawn."""
        subset = [h for h in hours if predicate(h)]
        if len(subset) < 2:
            raise RuntimeError(f"{name}: {len(subset)} hours is not enough to fit a line")
        return subset

    shipped = shipped_candidate(hours)
    candidates: list[Candidate] = [shipped]
    for name, regime, predicate in PERIOD_SUBSETS:
        columns = _columns(fittable(name, predicate))
        candidates.append(
            Candidate(
                name=name,
                height=shipped.height,
                period=fit_line("swell_period_s", name, regime, *columns["swell_period_s"]),
            )
        )
    for name, regime, predicate in SUBSETS:
        columns = _columns(fittable(name, predicate))
        candidates.append(
            Candidate(
                name=name,
                height=fit_line(
                    "significant_wave_height_m", name, regime, *columns["significant_wave_height_m"]
                ),
                period=fit_line("swell_period_s", name, regime, *columns["swell_period_s"]),
            )
        )

    columns = _columns(hours)
    all_hours_period = fit_line(
        "swell_period_s", "regime-aware", "every overlapping hour", *columns["swell_period_s"]
    )
    candidates.append(
        Candidate(
            name="regime-aware",
            height=fit_hinge(
                "significant_wave_height_m",
                "regime-aware",
                f"every overlapping hour, hinged at {KNOT_M:g} m",
                *columns["significant_wave_height_m"],
                knot=KNOT_M,
            ),
            period=all_hours_period,
        )
    )
    return candidates


