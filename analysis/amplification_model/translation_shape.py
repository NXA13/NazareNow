def shipped_bars(candidate: Candidate) -> dict[str, float]:
    """The three wave bars a Pipeline Run would read, had this candidate been the fit.

    The rounding is `calibrate.translate`'s and belongs to it — height floored to
    `HEIGHT_STEP_M` because down is its permissive direction, periods to the one decimal the
    operational feed reports. It is restated rather than called because `translate` also
    translates the light-wind exemption, whose transform is fitted on a different pairing that
    no candidate here touches; handing it a stand-in to get three numbers back would put a
    fabricated wind figure into this module's output. `check()` pins this against the shipped
    file so the two cannot drift apart silently.
    """
    height = float(
        candidate.height.apply(np.array([FITTED_BARS["minimum_significant_wave_height_m"]]))[0]
    )
    watch = float(
        candidate.period.apply(np.array([FITTED_BARS["watch_minimum_swell_period_s"]]))[0]
    )
    go = float(candidate.period.apply(np.array([FITTED_BARS["go_call_minimum_swell_period_s"]]))[0])
    return {
        "minimum_significant_wave_height_m": int(height / calibrate.HEIGHT_STEP_M)
        * calibrate.HEIGHT_STEP_M,
        "watch_minimum_swell_period_s": round(watch, 1),
        "go_call_minimum_swell_period_s": round(go, 1),
    }


