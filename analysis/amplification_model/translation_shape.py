@dataclass(frozen=True)
class Candidate:
    """One shape of Translation, for both quantities the Amplification Model restates."""

    name: str
    height: Shape
    period: Shape

    @property
    def shippable(self) -> bool:
        """Whether `fit_translations()` could return this without changing its contract."""
        return self.height.as_translation() is not None and self.period.as_translation() is not None


SUBSETS: tuple[tuple[str, str, Callable[[measure.Paired], bool]], ...] = (
    (
        "shipped",
        f"operational Swell height >= {measure.BIG_SWELL_HEIGHT_M:g} m",
        lambda h: h.operational_height >= measure.BIG_SWELL_HEIGHT_M,
    ),
    ("all-hours", "every overlapping hour", lambda h: True),
    (
        "combined-sea-3m",
        f"reanalysis Combined Sea >= {KNOT_M:g} m",
        lambda h: h.reanalysis_combined_sea >= KNOT_M,
    ),
    (
        "band-fitted",
        f"reanalysis Combined Sea {BAND_M[0]:g}-{BAND_M[1]:g} m",
        lambda h: BAND_M[0] <= h.reanalysis_combined_sea < BAND_M[1],
    ),
)
"""The subset each single-line candidate is fitted on.

`shipped` is first and is the shipped fit re-derived here rather than read from
`amplification.json`, so that every candidate in the table is built by the same code from the
same hours and any difference between them is the subset and nothing else. `check()` requires
it to reproduce the shipped constants.

**`shipped` selects on operational Swell height, not on Combined Sea**, and that is the code
rather than a transcription slip — `measure.fit_translations` filters `operational_height`,
which is Open-Meteo's `swell_wave_height`. `combined-sea-3m` is the same bar read the way
`train.py:95-101`, `amplification.json` and #52's own body all describe it, and it is a
different 4,941 hours. CONTEXT.md keeps Combined Sea and Swell apart for exactly this reason.
"""


PAIRINGS: dict[
    str,
    tuple[
        Callable[[measure.Paired], float],
        Callable[[measure.Paired], float],
        Callable[[Candidate], Shape],
    ],
] = {
    "significant_wave_height_m": (
        lambda h: h.reanalysis_combined_sea,
        lambda h: h.operational_combined_sea,
        lambda candidate: candidate.height,
    ),
    "swell_period_s": (
        lambda h: h.combined_period,
        lambda h: h.operational_period,
        lambda candidate: candidate.period,
    ),
}
"""The two quantities a Translation is fitted between, and where each lives.

Named once because three places need it and they must not drift: the fitting, the error
measurement in section 2, and the restatement at scoring time. Two of them reading the pairing
differently is exactly the class of defect `served_path.check` exists to catch between the two
feature encodings.
"""


def _columns(hours: list[measure.Paired]) -> dict[str, tuple[list[float], list[float]]]:
    """Each pairing drawn out of a subset of hours, ready to fit."""
    return {
        quantity: ([source(h) for h in hours], [target(h) for h in hours])
        for quantity, (source, target, _) in PAIRINGS.items()
    }


def build_candidates(hours: list[measure.Paired]) -> list[Candidate]:
    """Every shape under test, fitted on the same overlap hours.

    The regime-aware candidate hinges the **height** transform only, and takes the all-hours
    line for period. Hinging the period transform on its own period has no principled knot,
    and hinging it on Combined Sea — the regime that actually matters — would make the
    restated period jump as the sea crosses 3 m, which is a worse defect than the one being
    fixed. Combined Sea is also where the question lives: it carries a standardised
    coefficient of 1.089 against swell period's 0.057 (`output/feature_reliance.csv`).
    """
    candidates: list[Candidate] = []
    for name, regime, predicate in SUBSETS:
        subset = [h for h in hours if predicate(h)]
        if len(subset) < 2:
            raise RuntimeError(f"{name}: {len(subset)} hours is not enough to fit a line")
        columns = _columns(subset)
        candidates.append(
            Candidate(
                name=name,
                height=fit_line(
                    "significant_wave_height_m", name, regime, *columns["significant_wave_height_m"]
                ),
                period=fit_line("swell_period_s", name, regime, *columns["swell_period_s"]),
            )
        )

    columns = _columns(hours)
    all_hours_period = fit_line(
        "swell_period_s", "regime-aware", "every overlapping hour", *columns["swell_period_s"]
    )
    candidates.append(
        Candidate(
            name="regime-aware",
            height=fit_hinge(
                "significant_wave_height_m",
                "regime-aware",
                f"every overlapping hour, hinged at {KNOT_M:g} m",
                *columns["significant_wave_height_m"],
                knot=KNOT_M,
            ),
            period=all_hours_period,
        )
    )
    return candidates


