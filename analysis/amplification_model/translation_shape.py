@dataclass(frozen=True)
class Segment:
    """One straight piece of a transform, and the scatter left around it.

    `lower` is in reanalysis units — the side the transform maps *from* — and is `-inf` for
    the first segment so that a single-line shape is a one-segment shape rather than a
    special case.
    """

    lower: float
    slope: float
    intercept: float
    residual_rmse: float
    n: int


@dataclass(frozen=True)
class Shape:
    """A fitted transform from a reanalysis reading to the operational equivalent.

    Generalises `measure.Translation` in exactly one direction: it may be more than one line.
    Everything else is deliberately kept identical, because an alternative that could not be
    consumed by both `LearnedAmplification._restate` and `calibrate.translate` is not a
    candidate — it is a different ticket. `as_translation()` is what makes that concrete: a
    one-segment shape hands back the shipped type unchanged, and a multi-segment one refuses,
    which is the honest statement of what adopting it would cost.
    """

    variable: str
    name: str
    regime: str
    segments: tuple[Segment, ...]

    def __post_init__(self) -> None:
        if not self.segments:
            raise ValueError("a shape needs at least one segment")
        if any(segment.slope <= 0 for segment in self.segments):
            # Every consumer inverts this transform. A flat or descending segment makes the
            # inverse undefined or non-monotone, which would restate a larger sea as a
            # smaller one somewhere in the range.
            raise ValueError(f"{self.name}: a segment does not increase, so it cannot invert")

    @property
    def n(self) -> int:
        return max(segment.n for segment in self.segments)

    def _index(self, xs: np.ndarray) -> np.ndarray:
        """Which segment each reanalysis-side value falls in."""
        bounds = np.array([segment.lower for segment in self.segments[1:]])
        return np.searchsorted(bounds, xs, side="right")

    def apply(self, xs: np.ndarray) -> np.ndarray:
        """Reanalysis in, operational out."""
        xs = np.asarray(xs, dtype=float)
        index = self._index(xs)
        slope = np.array([s.slope for s in self.segments])[index]
        intercept = np.array([s.intercept for s in self.segments])[index]
        return slope * xs + intercept

    def scatter(self, xs: np.ndarray) -> np.ndarray:
        """The residual RMSE that applies at each reanalysis-side value."""
        xs = np.asarray(xs, dtype=float)
        return np.array([s.residual_rmse for s in self.segments])[self._index(xs)]

    def invert(self, ys: np.ndarray) -> np.ndarray:
        """Operational in, reanalysis out — the direction a Pipeline Run needs.

        The segment is chosen on the operational side, by mapping each boundary through the
        transform. `fit_hinge` joins its lines *at* the knot, so the two readings of the
        boundary agree and the inverse is the genuine inverse rather than an approximation of
        one; `__post_init__` rules out the non-monotone case that would break it.
        """
        ys = np.asarray(ys, dtype=float)
        boundaries = np.array(
            [segment.slope * segment.lower + segment.intercept for segment in self.segments[1:]]
        )
        index = np.searchsorted(boundaries, ys, side="right")
        slope = np.array([s.slope for s in self.segments])[index]
        intercept = np.array([s.intercept for s in self.segments])[index]
        return (ys - intercept) / slope

    def as_translation(self) -> measure.Translation | None:
        """The shipped type, when this shape is expressible in it."""
        if len(self.segments) != 1:
            return None
        segment = self.segments[0]
        return measure.Translation(
            variable=self.variable,
            slope=segment.slope,
            intercept=segment.intercept,
            n=segment.n,
            residual_rmse=segment.residual_rmse,
            regime=self.regime,
        )

    def describe(self) -> str:
        if len(self.segments) == 1:
            segment = self.segments[0]
            return (
                f"operational = {segment.slope:.4f} x reanalysis {segment.intercept:+.4f} "
                f"(fitted on {segment.n} {self.regime}, residual RMSE "
                f"{segment.residual_rmse:.3f})"
            )
        pieces = []
        for index, segment in enumerate(self.segments):
            where = (
                f"below {self.segments[index + 1].lower:g}"
                if index + 1 < len(self.segments)
                else f"at or above {segment.lower:g}"
            )
            pieces.append(
                f"{where}: {segment.slope:.4f} x reanalysis {segment.intercept:+.4f} "
                f"(n {segment.n}, residual RMSE {segment.residual_rmse:.3f})"
            )
        return f"piecewise, {self.regime} — " + "; ".join(pieces)


def _shape_from(variable: str, translation: dict) -> Shape:
    """A one-segment shape from an `amplification.json` translation block."""
    return Shape(
        variable=variable,
        name="shipped",
        regime=f"{translation['fitted_on_hours']} hours, per amplification.json",
        segments=(
            Segment(
                lower=-math.inf,
                slope=float(translation["slope"]),
                intercept=float(translation["intercept"]),
                residual_rmse=float(translation["residual_rmse"]),
                n=int(translation["fitted_on_hours"]),
            ),
        ),
    )


def fit_line(variable: str, name: str, regime: str, xs: list[float], ys: list[float]) -> Shape:
    """One least-squares line, through the same arithmetic the shipped Translation uses."""
    slope, intercept, rmse = measure.least_squares(xs, ys)
    return Shape(
        variable=variable,
        name=name,
        regime=regime,
        segments=(
            Segment(
                lower=-math.inf,
                slope=slope,
                intercept=intercept,
                residual_rmse=rmse,
                n=len(xs),
            ),
        ),
    )


def fit_hinge(
    variable: str, name: str, regime: str, xs: list[float], ys: list[float], knot: float
) -> Shape:
    """Two lines joined at `knot`, fitted together in one least-squares solve.

    Fitted as `a + b*x + c*max(0, x - knot)` rather than as two independent regressions. Two
    independent fits would leave a step at the join, and a transform with a step is not
    invertible there — two different seas would restate to the same reading, and one reading
    would restate to two seas. Sharing the intercept makes continuity structural rather than
    something to check afterwards.

    The knot is fixed rather than searched. Searching it on the same hours it is scored on
    would fit the knot to the noise, and 3 m is the boundary the question is about.
    """
    x = np.asarray(xs, dtype=float)
    y = np.asarray(ys, dtype=float)
    hinge = np.maximum(0.0, x - knot)
    if not (hinge > 0).any() or not (hinge == 0).any():
        raise ValueError(f"{name}: every hour falls on one side of the {knot:g} knot")
    design = np.column_stack([np.ones_like(x), x, hinge])
    (base, slope_low, step), *_ = np.linalg.lstsq(design, y, rcond=None)

    below, above = x < knot, x >= knot
    residuals = y - design @ np.array([base, slope_low, step])
    return Shape(
        variable=variable,
        name=name,
        regime=regime,
        segments=(
            Segment(
                lower=-math.inf,
                slope=float(slope_low),
                intercept=float(base),
                residual_rmse=float(np.sqrt(np.mean(residuals[below] ** 2))),
                n=int(below.sum()),
            ),
            Segment(
                lower=knot,
                slope=float(slope_low + step),
                # Continuity at the knot: the upper line is the lower one, pivoted there.
                intercept=float(base - step * knot),
                residual_rmse=float(np.sqrt(np.mean(residuals[above] ** 2))),
                n=int(above.sum()),
            ),
        ),
    )


