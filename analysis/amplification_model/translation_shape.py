def pin_against_shipped(shipped: Candidate, parameters: dict) -> str:
    """Refuse to report anything unless the `shipped` candidate really is the shipped one.

    Every figure in this module is a comparison against `shipped`, and `shipped` is re-derived
    here from the overlap hours rather than read out of `amplification.json` — so that all five
    candidates are built by one piece of code from one set of hours and differ only in their
    subset. That is worth having, and it is only worth having if the re-derivation lands on the
    constants the backend actually applies. If it does not, the whole table is measuring this
    module against itself.
    """
    published = parameters["translations"]
    for variable, shape in (
        ("significant_wave_height_m", shipped.height),
        ("swell_period_s", shipped.period),
    ):
        segment = shape.segments[0]
        for label, here, there in (
            ("slope", segment.slope, published[variable]["slope"]),
            ("intercept", segment.intercept, published[variable]["intercept"]),
            ("residual RMSE", segment.residual_rmse, published[variable]["residual_rmse"]),
            ("hours", float(segment.n), float(published[variable]["fitted_on_hours"])),
        ):
            if abs(here - there) > 1e-9:
                raise RuntimeError(
                    f"the re-derived shipped Translation does not match amplification.json: "
                    f"{variable} {label} is {here!r} here against {there!r} shipped. Either the "
                    "overlap cache has changed since the model was exported, or this module "
                    "fits a different subset from `measure.fit_translations`."
                )
    return "The `shipped` candidate re-derives amplification.json's constants exactly.\n"


def pin_against_served_path(
    shipped: Candidate, parameters, frame, target: np.ndarray, trials: int
) -> str:
    """Reproduce `output/served_path_scores.csv` by running this module as the shipped path.

    The generalisation here separates two things `served_path.py` holds together — the
    transform that generates the operational series and the transform the model inverts — and
    that separation is the whole argument of this module. Collapsing it back, by generating
    with `shipped` and inverting with `shipped`, must land exactly on the published served
    figures. If it does not, the generalisation changed the arithmetic rather than only
    widening it, and every alternative scored against those figures would be scored against a
    different calculation that happens to look alike.
    """
    _, collected = score_candidates(
        parameters,
        frame,
        target,
        [shipped],
        Reconstruction(generator=shipped),
        trials=trials,
    )
    published = {row["subset"]: row for row in _published_served()}
    for band, results in collected.items():
        if band not in published:
            continue
        for label, key in (("baseline", "served_baseline_mae"), ("shipped", "served_learned_mae")):
            here = float(np.mean(results[label]))
            there = float(published[band][key])
            if abs(here - there) > 5e-5:
                raise RuntimeError(
                    f"scored as the shipped path, {band} {label} is {here:.4f} here against "
                    f"{there:.4f} in served_path_scores.csv — the generalisation moved the "
                    "arithmetic, not just its inputs"
                )
    return (
        f"Run as the shipped path it reproduces served_path_scores.csv over {trials} trials, "
        "so the\nalternatives below are comparable with the published served figures rather "
        "than a\nseparate calculation.\n"
    )


def _published_served() -> list[dict]:
    with served_path.OUTPUT.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _write(path: Path, rows: list[dict]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return path


def reconstructions(by_name: dict[str, Candidate], generator_name: str) -> list[Reconstruction]:
    """Every version of the served path this module reports, in the order they build on each other.

    The published served figures come from the first. The headline comes from the second. The
    difference between the two is the reconstruction's own contribution, which is the quantity
    #52 needs and which no single run can show.
    """
    generator = by_name[generator_name]
    return [
        Reconstruction(generator=by_name["shipped"]),
        Reconstruction(generator=generator),
        Reconstruction(generator=generator, scatter="none"),
        Reconstruction(generator=generator, scatter="proportional"),
    ]


def build(generator_name: str, trials: int) -> int:
    parameters, frame = served_path.load()
    target = frame["proxy_target_height_m"].to_numpy()
    hours = measure.pair_hours(reanalysis.IBI)
    candidates = build_candidates(hours)
    by_name = {candidate.name: candidate for candidate in candidates}
    if generator_name not in by_name:
        raise SystemExit(f"unknown generator {generator_name!r}; choose from {sorted(by_name)}")
    names = [candidate.name for candidate in candidates]

    shipped = by_name["shipped"]
    fitted_hours = [h for h in hours if h.operational_height >= measure.BIG_SWELL_HEIGHT_M]
    fitted_floor = float(np.percentile([h.reanalysis_combined_sea for h in fitted_hours], 1))

    print(f"Overlap hours: {len(hours):,}   held-out rows: {len(frame):,}\n")
    print(pin_against_shipped(shipped, parameters))
    print(pin_against_served_path(shipped, parameters, frame, target, trials))
    print("The transforms\n")
    for candidate in candidates:
        flag = "" if candidate.shippable else "   [not expressible as a Translation]"
        print(f"  {candidate.name:<16} {candidate.height.regime}{flag}")
        print(f"      height  {candidate.height.describe()}")
        print(f"      period  {candidate.period.describe()}")

    # --- 1 -----------------------------------------------------------------------------------
    print(f"\n{'=' * 98}\n1. How much of each band the shipped Translation was never fitted on\n")
    print(
        f"The shipped subset is selected on operational Swell height, so measured in Combined "
        f"Sea it\nreaches down to {fitted_floor:.2f} m at its 1st percentile — the floor of its "
        f"real support, against\nthe {KNOT_M:g} m the ticket, `train.py` and `amplification.json` "
        f"all name.\n"
    )
    support_rows = support(frame, target, fitted_floor)
    print(f"{'band':<32}{'rows':>8}{'below 3.00 m':>14}{'below support':>15}{'median input':>14}")
    for row in support_rows:
        print(
            f"{row.band:<32}{row.rows:>8,}{row.below_nominal:>13.1%}{row.below_support:>15.1%}"
            f"{row.median_input:>14.2f}"
        )
    _write(
        SUPPORT_CSV,
        [
            {
                "band": row.band,
                "rows": row.rows,
                "input_below_3m": round(row.below_nominal, 4),
                "input_below_fitted_support": round(row.below_support, 4),
                "fitted_support_floor_m": round(fitted_floor, 4),
                "median_input_combined_sea_m": round(row.median_input, 4),
            }
            for row in support_rows
        ],
    )

    # --- 2 -----------------------------------------------------------------------------------
    print(
        f"\n{'=' * 98}\n2. Each transform against the pairing it claims to describe — "
        f"observed, not reconstructed\n"
    )
    print(
        "Both products really reported on every one of these hours, so this table carries no\n"
        "assumption at all. Bands are the *input* Combined Sea, over the overlap; every other\n"
        "table here bands the measured target over the held-out seasons.\n"
    )
    errors = pairing_error(hours, candidates)
    _write(
        PAIRING_CSV,
        [
            {
                "quantity": row.quantity,
                "candidate": row.candidate,
                "input_combined_sea_band": row.band,
                "hours": row.n,
                "bias": round(row.bias, 4),
                "rmse": round(row.rmse, 4),
            }
            for row in errors
        ],
    )
    for quantity in ("significant_wave_height_m", "swell_period_s"):
        print(f"  {quantity} — bias / RMSE against the operational reading\n")
        print(f"  {'input band':<14}{'hours':>8}" + "".join(f"{name:>18}" for name in names))
        bands_seen = [
            row.band for row in errors if row.candidate == names[0] and row.quantity == quantity
        ]
        for band in bands_seen:
            row_for = {
                row.candidate: row
                for row in errors
                if row.quantity == quantity and row.band == band
            }
            line = f"  {band:<14}{row_for[names[0]].n:>8,}"
            for name in names:
                line += f"{f'{row_for[name].bias:+.3f} / {row_for[name].rmse:.3f}':>18}"
            print(line)
        print()

    # --- 3 -----------------------------------------------------------------------------------
    runs = reconstructions(by_name, generator_name)
    scored: dict[str, dict[str, dict[str, float]]] = {}
    shape_rows: list[dict] = []
    bands: dict[str, np.ndarray] = {}
    for reconstruction in runs:
        bands, collected = score_candidates(
            parameters, frame, target, candidates, reconstruction, trials=trials
        )
        gains: dict[str, dict[str, float]] = {}
        for band in bands:
            baseline = float(np.mean(collected[band]["baseline"]))
            gains[band] = {"baseline": baseline}
            for name in names:
                learned = float(np.mean(collected[band][name]))
                gains[band][name] = baseline - learned
                spread = np.array(collected[band]["baseline"]) - np.array(collected[band][name])
                low, high = np.percentile(spread, [5, 95])
                shape_rows.append(
                    {
                        "generator": reconstruction.generator.name,
                        "scatter": reconstruction.scatter,
                        "candidate": name,
                        "band": band,
                        "rows": int(bands[band].sum()),
                        "served_baseline_mae": round(baseline, 4),
                        "served_learned_mae": round(learned, 4),
                        "served_gain_m": round(baseline - learned, 4),
                        "served_gain_p5": round(float(low), 4),
                        "served_gain_p95": round(float(high), 4),
                    }
                )
        scored[reconstruction.label] = gains
    _write(SHAPES_CSV, shape_rows)

    headline = runs[1]
    print(f"{'=' * 98}\n3. Every candidate on the served path — {headline.label}\n")
    print("Positive means the learned Amplification Model is closer to the buoy.\n")
    print(f"{'band':<32}{'rows':>7}{'baseline MAE':>14}" + "".join(f"{name:>16}" for name in names))
    for band in bands:
        gains = scored[headline.label][band]
        line = f"{band:<32}{int(bands[band].sum()):>7,}{gains['baseline']:>14.4f}"
        for name in names:
            line += f"{gains[name]:>+16.4f}"
        print(line)

    # --- 4 -----------------------------------------------------------------------------------
    print(f"\n{'=' * 98}\n4. Where the published figure for each band comes from\n")
    print(
        "Six readings of the same band, each one assumption further out than the last. The gap\n"
        "between `published` and `fair gen` is the reconstruction's own contribution to the\n"
        "published figure; the gap between `fair gen` and `best alt` is all any change of shape\n"
        "could buy; and `no scatter` against `best alt` is what the assumed residual costs. What\n"
        "is left against `scored` is none of those three — it is the real difference between the\n"
        "two products, which shifts the baseline's reading and cannot be transformed away.\n\n"
        "`best alt`, `no scatter` and `sized scatter` are the best candidate *for that band*,\n"
        "named in the last column. It is not always an alternative: where it reads `shipped`,\n"
        "nothing beat the shipped fit.\n"
    )
    published = {row["subset"]: row for row in _published_served()}
    ladder = (
        ("scored", "no Translation step at all — `train.py`'s table", None, None),
        (
            "published",
            "served_path.py: generated and inverted by the shipped line",
            runs[0].label,
            "shipped",
        ),
        (
            "fair gen",
            "same shipped line, generated by one that fits every sea",
            runs[1].label,
            "shipped",
        ),
        ("best alt", "the best alternative transform, same generator", runs[1].label, None),
        ("no scatter", "the offset alone, with the residual switched off", runs[2].label, None),
        ("sized scatter", "the residual grown with the sea instead of flat", runs[3].label, None),
    )
    for short, meaning, _, _ in ladder:
        print(f"  {short:<15}{meaning}")
    print()
    print(f"{'band':<30}" + "".join(f"{short:>13}" for short, *_ in ladder) + "   best alternative")
    for band in bands:
        if band not in published:
            continue
        best = max(names, key=lambda name: scored[runs[1].label][band][name])
        line = f"{band:<30}"
        for _, _, label, candidate in ladder:
            value = (
                float(published[band]["scored_gain_m"])
                if label is None
                else scored[label][band][candidate or best]
            )
            line += f"{value:>+13.4f}"
        print(line + f"   {best}")

    # --- 5 -----------------------------------------------------------------------------------
    print(f"\n{'=' * 98}\n5. What adopting each candidate would do to the shipped bars\n")
    print(
        "`calibrate.py` restates the fitted bars through this same fit, so no candidate here is\n"
        "only an Amplification Model change. Fitted bars, in reanalysis units: "
        + ", ".join(f"{name.split('_')[0]} {value:g}" for name, value in FITTED_BARS.items())
        + ".\n"
    )
    current = json.loads(THRESHOLDS.read_text(encoding="utf-8"))
    print(f"{'candidate':<16}{'height m':>12}{'Watch s':>12}{'Go Call s':>12}   shippable")
    bar_rows: list[dict] = []
    for candidate in candidates:
        bars = shipped_bars(candidate)
        moved = {name: bars[name] - float(current[name]) for name in FITTED_BARS}
        print(
            f"{candidate.name:<16}"
            f"{bars['minimum_significant_wave_height_m']:>7.2f}"
            f"{moved['minimum_significant_wave_height_m']:>+5.2f}"
            f"{bars['watch_minimum_swell_period_s']:>7.1f}"
            f"{moved['watch_minimum_swell_period_s']:>+5.1f}"
            f"{bars['go_call_minimum_swell_period_s']:>7.1f}"
            f"{moved['go_call_minimum_swell_period_s']:>+5.1f}"
            f"   {'yes' if candidate.shippable else 'no — two lines'}"
        )
        bar_rows.append(
            {
                "candidate": candidate.name,
                "shippable_as_translation": "yes" if candidate.shippable else "no",
                **{name: bars[name] for name in FITTED_BARS},
                **{f"moved_{name}": round(moved[name], 4) for name in FITTED_BARS},
            }
        )
    _write(BARS_CSV, bar_rows)

    print(
        f"\nwrote {SUPPORT_CSV.relative_to(ROOT)}, {PAIRING_CSV.relative_to(ROOT)},\n"
        f"      {SHAPES_CSV.relative_to(ROOT)}, {BARS_CSV.relative_to(ROOT)}"
    )
    print(
        "\nSection 2 is observed. Sections 3 to 5 are bounds: the serving provider has no\n"
        "historical archive at this location, so the operational series is reconstructed. See\n"
        "the module docstring and `README.md`."
    )
    return 0


